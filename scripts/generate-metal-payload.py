#!/usr/bin/env python3
"""Generate xnu/bsd/kern/b2l_metal_payload.h from built b2l-metal-v95 outputs."""
import argparse
from pathlib import Path
import struct
import zlib

MH_MAGIC_64 = 0xfeedfacf
CPU_TYPE_ARM64 = 0x0100000c

FILES = (
    ("B2LMetalv95", "b2l_metal_bundle_bin", True),
    ("B2LMetalv95-Info.plist", "b2l_metal_bundle_plist", False),
    ("libhakiosmetal.dylib", "b2l_metal_libhakiosmetal", True),
    ("libhakiosair.dylib", "b2l_metal_libhakiosair", True),
)


def validate_file(name: str, data: bytes, is_macho: bool) -> None:
    if not data:
        raise ValueError(f"{name}: empty file")
    if is_macho:
        if len(data) < 32:
            raise ValueError(f"{name}: too short for Mach-O header")
        magic, cpu = struct.unpack_from("<Ii", data, 0)
        if magic != MH_MAGIC_64 or cpu != CPU_TYPE_ARM64:
            raise ValueError(f"{name}: expected thin arm64 Mach-O, got magic=0x{magic:x} cpu=0x{cpu:x}")
    else:
        if b"B2LMetalUIDevice" not in data or b"<plist" not in data:
            raise ValueError(f"{name}: unexpected Info.plist content")


def format_array(symbol: str, zdata: bytes, raw_len: int) -> str:
    lines = [
        f"static const size_t {symbol}_raw_len = {raw_len}u;",
        f"static const unsigned char {symbol}_z[] = {{",
    ]
    for off in range(0, len(zdata), 16):
        chunk = ",".join(f"0x{b:02x}" for b in zdata[off:off + 16])
        lines.append(f"  {chunk},")
    lines.append("};")
    return "\n".join(lines)


def generate(input_dir: Path, output_path: Path) -> None:
    sections = [
        "/* Generated by scripts/generate-metal-payload.py; do not edit by hand. */",
        "#ifndef B2L_METAL_PAYLOAD_H",
        "#define B2L_METAL_PAYLOAD_H",
        "#define B2L_METAL_EMBEDDED 1",
    ]
    for filename, symbol, is_macho in FILES:
        path = input_dir / filename
        if not path.is_file():
            raise FileNotFoundError(f"Missing Metal artifact file: {path}")
        raw = path.read_bytes()
        validate_file(filename, raw, is_macho)
        zdata = zlib.compress(raw, 9)
        sections.append(format_array(symbol, zdata, len(raw)))
    sections.append("#endif /* B2L_METAL_PAYLOAD_H */")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(sections) + "\n", encoding="utf-8")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", type=Path, required=True, help="Directory with b2l-metal-v95 build artifacts")
    p.add_argument("--output", type=Path, required=True, help="Destination b2l_metal_payload.h path")
    args = p.parse_args()
    generate(args.input, args.output)


if __name__ == "__main__":
    main()
