"""Build b2l-bluetool-v5.dylib (arm64e, userspace/b2l-bluetool.c) and its kernel seed header."""
from pathlib import Path
import argparse, hashlib, subprocess, tempfile, struct

r = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--output', type=Path, required=True)
a = p.parse_args()

sdk = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-path'], text=True).strip()
sdk_ver = subprocess.check_output(['xcrun', '--sdk', 'iphoneos', '--show-sdk-version'], text=True).strip()

MG_TBD = """--- !tapi-tbd
tbd-version: 4
targets: [ arm64e-ios ]
install-name: '/usr/lib/libMobileGestalt.dylib'
exports:
  - targets: [ arm64e-ios ]
    symbols: [ _MGIsDeviceOneOfType ]
...
"""

with tempfile.TemporaryDirectory(prefix='b2l-bt-') as td:
    lib = Path(td) / 'b2l-bluetool-v5.dylib'
    tbd = Path(td) / 'libMobileGestalt.tbd'
    tbd.write_text(MG_TBD)
    subprocess.run([
        'xcrun', '--sdk', 'iphoneos', 'clang',
        '-target', f'arm64e-apple-ios{sdk_ver}', '-isysroot', sdk,
        '-Os', '-Wall', '-Wextra', '-Werror',
        '-dynamiclib', '-install_name', '/usr/local/lib/b2l-bluetool-v5.dylib',
        str(r / 'userspace/b2l-bluetool.c'), str(tbd), '-o', str(lib)
    ], check=True)
    subprocess.run(['/usr/bin/codesign', '--force', '--sign', '-', '--identifier', 'dev.b2l.bluetool', str(lib)], check=True)
    subprocess.run(['/usr/bin/codesign', '--verify', str(lib)], check=True)
    data = lib.read_bytes()

cputype, subtype, ftype = struct.unpack_from('<III', data, 4)
if cputype != 0x100000c or subtype & 0xffffff != 2 or ftype != 6:
    raise SystemExit('not an arm64e dylib')
if len(data) > 512 * 1024:
    raise SystemExit('dylib too large')

a.output.write_text(
    '/* Generated by scripts/build-bluetool-dylib.py: b2l-bluetool-v5.dylib (userspace/b2l-bluetool.c). */\n'
    'static const unsigned char b2l_bt_tool_dylib[] = {\n' +
    ''.join(' ' + ','.join('0x%02x' % x for x in data[i:i + 20]) + ',\n' for i in range(0, len(data), 20)) +
    '};\n'
)
print('Built b2l-bluetool-v5.dylib:', len(data), 'bytes; sha256', hashlib.sha256(data).hexdigest())
